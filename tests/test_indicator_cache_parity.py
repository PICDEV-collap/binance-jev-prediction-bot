@pytest.mark.parametrize("length,delta,emas,rsi,atr", REFERENCE)
def test_indicator_outputs_match_original_with_changing_active_candle(length, delta, emas, rsi, atr):
    rng = random.Random(217)
    prices = [100 + rng.uniform(-10, 10) for _ in range(length)]
    if prices:
        prices[-1] += delta
    candles = [Candle(i*60, v, v+2+(i%3), v-1-(i%2), v) for i,v in enumerate(prices)]
    assert [compute_ema(prices, p) for p in (9,21,50)] == pytest.approx(emas, abs=1e-12)
    assert compute_rsi(prices) == rsi
    assert compute_atr(candles) == atr


def test_completed_history_is_reused_and_cache_is_bounded():
    for cache in (_ema_history, _rsi_history, _atr_history):
        cache.cache_clear()
    prices = [100 + (i%7) for i in range(61)]
    candles = [Candle(i*60, v, v+2, v-2, v) for i,v in enumerate(prices)]
    for value in range(100, 200):
        prices[-1] = value
        candles[-1].close = value
        candles[-1].high = value+2
        candles[-1].low = value-2
        compute_ema(prices, 9)
        compute_rsi(prices)
        compute_atr(candles)
    for cache in (_ema_history, _rsi_history, _atr_history):
        assert cache.cache_info().hits == 99
        assert cache.cache_info().currsize == 1
    for shift in range(300):
        compute_ema([v+shift for v in prices], 9)
    assert _ema_history.cache_info().currsize == 256
